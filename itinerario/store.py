import json
import sqlite3
from hashlib import sha256
from secrets import token_urlsafe
from datetime import date, timedelta
from pathlib import Path
from uuid import uuid4

from .models import Snapshot

SCHEMA = """
CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY, value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS jobs (
    id BIGINT PRIMARY KEY, owner BIGINT NOT NULL, created TEXT NOT NULL,
    stage TEXT NOT NULL DEFAULT 'queued', payload TEXT,
    delivery TEXT, attempts INTEGER NOT NULL DEFAULT 0, retry_after TEXT
);
CREATE INDEX IF NOT EXISTS jobs_stage ON jobs(stage, id);
CREATE TABLE IF NOT EXISTS messages (
    id {message_id} PRIMARY KEY, owner BIGINT NOT NULL, created TEXT NOT NULL, role TEXT NOT NULL, text TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS message_history ON messages(owner, id);
CREATE TABLE IF NOT EXISTS reports (
    id TEXT PRIMARY KEY, owner BIGINT NOT NULL, created TEXT NOT NULL, title TEXT NOT NULL,
    data TEXT NOT NULL, pdf {binary_type} NOT NULL
);
CREATE INDEX IF NOT EXISTS report_history ON reports(owner, created);
CREATE TABLE IF NOT EXISTS active_report (
    owner BIGINT PRIMARY KEY, report_id TEXT NOT NULL REFERENCES reports(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS quotas (
    owner BIGINT NOT NULL, day TEXT NOT NULL, category TEXT NOT NULL, used INTEGER NOT NULL,
    PRIMARY KEY(owner, day, category)
);
CREATE TABLE IF NOT EXISTS invitations (
    digest TEXT PRIMARY KEY, expires TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS guests (
    owner BIGINT PRIMARY KEY
);
"""


class Store:
    def __init__(self, root: Path, database_url: str = ""):
        self.postgres = bool(database_url)
        if self.postgres:
            import psycopg
            from psycopg.rows import dict_row

            try:
                self.db = psycopg.connect(database_url, autocommit=True, row_factory=dict_row, connect_timeout=10)
                with self.db.transaction():
                    self.db.execute("SELECT pg_advisory_xact_lock(229606172)")
                    self.db.execute(SCHEMA.format(message_id="BIGINT GENERATED BY DEFAULT AS IDENTITY",
                                                  binary_type="BYTEA"))
            except psycopg.Error:
                raise ValueError("No se pudo abrir o preparar la base PostgreSQL.") from None
            return
        root.mkdir(parents=True, exist_ok=True)
        self.db = sqlite3.connect(root / "itinerario.sqlite3", timeout=5)
        self.db.row_factory = sqlite3.Row
        self.db.execute("PRAGMA journal_mode=WAL")
        self.db.execute("PRAGMA foreign_keys=ON")
        self.db.executescript(SCHEMA.format(message_id="INTEGER", binary_type="BLOB"))

    def _execute(self, statement: str, arguments: tuple = ()):
        if self.postgres:
            statement = statement.replace("?", "%s")
        return self.db.execute(statement, arguments)

    def _transaction(self):
        return self.db.transaction() if self.postgres else self.db

    def try_worker_lock(self) -> bool:
        if not self.postgres:
            return True
        row = self._execute("SELECT pg_try_advisory_lock(229606173) AS acquired").fetchone()
        return row["acquired"]

    def close(self):
        self.db.close()

    def offset(self, today: str) -> int | None:
        row = self._execute("SELECT value FROM settings WHERE key = 'offset'").fetchone()
        if row:
            offset, stamp = json.loads(row["value"])
            if date.fromisoformat(today) - date.fromisoformat(stamp) < timedelta(days=6):
                return offset
        return None

    def is_guest(self, owner: int) -> bool:
        return self._execute("SELECT 1 FROM guests WHERE owner=?", (owner,)).fetchone() is not None

    def invite(self, expires: str) -> str:
        code = token_urlsafe(18)
        with self._transaction():
            self._execute("INSERT INTO invitations VALUES (?, ?)", (sha256(code.encode()).hexdigest(), expires))
        return code

    def redeem(self, owner: int, code: str, now: str) -> bool:
        with self._transaction():
            result = self._execute(
                "DELETE FROM invitations WHERE digest=? AND expires>? RETURNING digest",
                (sha256(code.encode()).hexdigest(), now),
            ).fetchone()
            if result is None:
                return False
            self._execute("INSERT INTO guests VALUES (?) ON CONFLICT(owner) DO NOTHING", (owner,))
        return True

    def enqueue(self, updates: list[dict], now: str, allowed: frozenset[int], *, remember_offset: bool = True):
        if not updates:
            return
        with self._transaction():
            for update in updates:
                message = update.get("message") or {}
                owner = message.get("from", {}).get("id")
                chat = message.get("chat", {})
                if chat.get("type") != "private" or owner is None or chat.get("id") != owner:
                    continue
                command = (message.get("text") or "").split(maxsplit=1)
                access_command = bool(command and command[0].split("@")[0] in {"/start", "/miid"})
                if owner not in allowed and not access_command and not self.is_guest(owner):
                    continue
                self._execute(
                    "INSERT INTO jobs(id, owner, created, payload) VALUES (?, ?, ?, ?) ON CONFLICT(id) DO NOTHING",
                    (update["update_id"], owner, now, json.dumps(message, ensure_ascii=False)),
                )
            if remember_offset:
                self._execute(
                    "INSERT INTO settings VALUES ('offset', ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                    (json.dumps((max(update["update_id"] for update in updates) + 1, now[:10])),),
                )

    def recover(self):
        with self._transaction():
            self._execute(
                "UPDATE jobs SET stage='delivery', payload=NULL, delivery=? WHERE stage='working'",
                (json.dumps({"text": "El proceso se interrumpió. Reenviá el pedido si querés volver a intentarlo."}),),
            )

    def next_job(self):
        with self._transaction():
            row = self._execute(
                "UPDATE jobs SET stage='working' WHERE id = "
                "(SELECT id FROM jobs WHERE stage='queued' ORDER BY id LIMIT 1) "
                "AND stage='queued' RETURNING *"
            ).fetchone()
            return row

    def next_delivery(self, now: str):
        return self._execute(
            "SELECT * FROM jobs WHERE stage='delivery' AND (retry_after IS NULL OR retry_after <= ?) "
            "ORDER BY id LIMIT 1", (now,),
        ).fetchone()

    def deliver(self, job_id: int, delivery: dict, assistant_text: str = "", now: str = "",
                report: tuple[Snapshot, bytes] | None = None):
        with self._transaction():
            owner_row = self._execute("SELECT owner FROM jobs WHERE id=?", (job_id,)).fetchone()
            owner = owner_row["owner"]
            if report:
                snapshot, pdf = report
                report_id = uuid4().hex[:12]
                self._execute(
                    "INSERT INTO reports VALUES (?, ?, ?, ?, ?, ?)",
                    (report_id, owner, snapshot.created, snapshot.report.title, snapshot.model_dump_json(), pdf),
                )
                self._select_report(owner, report_id)
                delivery["report_id"] = report_id
            if assistant_text:
                self._execute("INSERT INTO messages(owner, created, role, text) VALUES (?, ?, ?, ?)",
                                (owner, now, "assistant", assistant_text))
            self._execute("UPDATE jobs SET stage='delivery', payload=NULL, delivery=? WHERE id=?",
                            (json.dumps(delivery, ensure_ascii=False), job_id))

    def finish(self, job_id: int):
        with self._transaction():
            self._execute("UPDATE jobs SET stage='done', delivery=NULL, payload=NULL WHERE id=?", (job_id,))

    def retry_delivery(self, job_id: int, retry_after: str):
        with self._transaction():
            self._execute("UPDATE jobs SET attempts=attempts+1, retry_after=? WHERE id=?", (retry_after, job_id))

    def history(self, owner: int, limit: int = 10):
        return list(reversed(self._execute(
            "SELECT role, text FROM messages WHERE owner=? ORDER BY id DESC LIMIT ?", (owner, limit),
        ).fetchall()))

    def remember(self, owner: int, now: str, text: str):
        with self._transaction():
            self._execute("INSERT INTO messages(owner, created, role, text) VALUES (?, ?, ?, ?)",
                            (owner, now, "user", text))

    def list_reports(self, owner: int, limit: int = 12):
        tie_breaker = "id" if self.postgres else "rowid"
        return self._execute(
            f"SELECT id, title, created FROM reports WHERE owner=? ORDER BY created DESC, {tie_breaker} DESC LIMIT ?",
            (owner, limit),
        ).fetchall()

    def _select_report(self, owner: int, report_id: str):
        self._execute(
            "INSERT INTO active_report VALUES (?, ?) ON CONFLICT(owner) DO UPDATE SET report_id=excluded.report_id",
            (owner, report_id),
        )

    def select_report(self, owner: int, report_id: str):
        with self._transaction():
            row = self.report(owner, report_id)
            if row:
                self._select_report(owner, report_id)
            return row

    def report(self, owner: int, report_id: str | None = None):
        if report_id is None:
            return self._execute(
                "SELECT reports.* FROM reports JOIN active_report ON active_report.report_id=reports.id "
                "WHERE reports.owner=? AND active_report.owner=?", (owner, owner),
            ).fetchone()
        return self._execute("SELECT * FROM reports WHERE owner=? AND id=?", (owner, report_id)).fetchone()

    def purge_owner(self, owner: int, keep_job: int):
        with self._transaction():
            self._execute("DELETE FROM messages WHERE owner=?", (owner,))
            self._execute("DELETE FROM reports WHERE owner=?", (owner,))
            self._execute(
                "UPDATE jobs SET stage='done', payload=NULL, delivery=NULL WHERE owner=? AND id<?",
                (owner, keep_job),
            )

    def prune(self, cutoff: str, job_cutoff: str):
        with self._transaction():
            self._execute("DELETE FROM messages WHERE created < ?", (cutoff,))
            self._execute("DELETE FROM reports WHERE created < ?", (cutoff,))
            self._execute("DELETE FROM jobs WHERE stage='done' AND created < ?", (job_cutoff,))
            self._execute("DELETE FROM quotas WHERE day < ?", (job_cutoff[:10],))
            self._execute("DELETE FROM invitations WHERE expires <= ?", (job_cutoff,))

    def reserve(self, day: str, category: str, limits: dict[int, int], *, units: int = 1) -> bool:
        if units < 1:
            raise ValueError("Quota units must be positive.")
        if any(units > limit for limit in limits.values()):
            return False
        with self._transaction():
            self._execute("SAVEPOINT reserve_quota")
            for owner, limit in limits.items():
                row = self._execute(
                    "INSERT INTO quotas VALUES (?, ?, ?, ?) ON CONFLICT(owner, day, category) "
                    "DO UPDATE SET used=quotas.used+excluded.used "
                    "WHERE quotas.used+excluded.used <= ? RETURNING used",
                    (owner, day, category, units, limit),
                ).fetchone()
                if row is None:
                    self._execute("ROLLBACK TO reserve_quota")
                    self._execute("RELEASE reserve_quota")
                    return False
            self._execute("RELEASE reserve_quota")
            return True
